// Builds the SNN column kernel (python/snn/column.cu + fdlibm.h) as WebAssembly and embeds it in
// bot/snn/kernelWasm.ts (base64, with the sources' hash), so the bot, the pipeline bundles and the trainer
// carry it without a separate file. Needs clang with the wasm32 target and wasm-ld (LLVM 15+).
//
//   npm run build:snn-wasm
// tests/snnKernel.test.ts fails when kernelWasm.ts was built from other sources than the ones in the repository.

import { execFileSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { kernelSourceHash } from '../bot/snn/kernelSource';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'snnwasm-')), 'column.wasm');
const cc = process.env.CC_WASM ?? 'clang';
execFileSync(cc, [
  '--target=wasm32', '-O3', '-msimd128', '-mbulk-memory', '-ffp-contract=off', '-fno-fast-math', '-nostdlib', '-x', 'c',
  '-Wl,--no-entry', '-Wl,--import-memory', '-Wl,--export=__heap_base', '-o', out, path.join(root, 'python/snn/column.cu'),
], { stdio: 'inherit' });
const b64 = fs.readFileSync(out).toString('base64');
const lines = b64.match(/.{1,120}/g)!.map((l) => `  '${l}',`).join('\n');
fs.writeFileSync(path.join(root, 'bot/snn/kernelWasm.ts'), `// Generated by scripts/buildSnnWasm.ts from python/snn/column.cu + fdlibm.h: do not edit (npm run build:snn-wasm).
export const KERNEL_SOURCE_HASH = '${kernelSourceHash(root)}';
export const KERNEL_WASM_B64 = [
${lines}
].join('');
`);
console.log(`bot/snn/kernelWasm.ts: ${fs.statSync(out).size} bytes of WebAssembly`);
